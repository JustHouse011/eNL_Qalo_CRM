import { expect, test, type Page } from '@playwright/test'
import { selectWorkspace } from '../helpers/workspaceSelector'

const bank = 'workspace-enl-mutual-bank'
const names = ['Becha Account', 'Nala Account', 'Temo Account', 'Temo Savings Account', 'iMbewu Savings Account', 'Pusha — Sole Proprietor', 'Pusha — Informal Trader', 'Owner — Private Company', 'Owner — Co-operative', 'Stokvel Account']
async function openHub(page: Page) {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 1536, height: 1100 })
  await page.goto('/overview')
  page.once('dialog', dialog => dialog.accept())
  await selectWorkspace(page, bank)
  await page.getByRole('link', { name: 'Banking Products', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Banking Products', exact: true })).toBeVisible()
}
const openBecha = (page: Page) => page.getByRole('button', { name: 'View details: Becha Account', exact: true }).click()
const qaloSnapshot = (page: Page) => page.evaluate(() => JSON.stringify(JSON.parse(localStorage.getItem('qalo-workspaces-v2')!).snapshots['workspace-qalo']))

test('product catalogue loads all images, searches, navigates support and adapts to both themes', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await openHub(page)
  for (const name of names) await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(page.locator('.enl-product-card [data-status="Coming Soon"]')).toHaveCount(4)
  const images = page.locator('.enl-product-card img')
  for (const image of await images.all()) {
    await image.scrollIntoViewIfNeeded()
    await expect.poll(() => image.evaluate(img => (img as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  }
  await page.locator('.enl-catalogue').evaluate(el => el.scrollTop = 0)
  await page.screenshot({ path: 'test-results/enl-products-light.png', animations: 'disabled' })
  const search = page.getByRole('textbox', { name: 'Search banking products' })
  await search.fill('sole proprietor')
  await expect(page.locator('.enl-product-card')).toHaveCount(1)
  await search.fill('confirm the current product information')
  await expect(page.locator('.enl-product-card')).toHaveCount(10)
  await search.fill('missing product')
  await expect(page.getByRole('heading', { name: 'No matching products' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear search' }).click()
  await openBecha(page)
  const drawer = page.getByRole('dialog', { name: 'Becha Account' })
  await expect(drawer).toBeVisible()
  await drawer.getByRole('tab', { name: 'Overview' }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(drawer.getByRole('tab', { name: 'Product Information' })).toHaveAttribute('aria-selected', 'true')
  await expect(drawer.getByText('Fees and charges', { exact: true })).toBeVisible()
  await drawer.getByRole('tab', { name: 'FAQs' }).click()
  await drawer.getByText('Where can I confirm the current product information?').click()
  await expect(drawer.getByText('Use the official eNL product link.', { exact: false })).toBeVisible()
  await drawer.getByRole('tab', { name: 'Related Support' }).click()
  await drawer.getByRole('link', { name: /Becha Account support application/ }).click()
  await expect(page).toHaveURL(/\/pipeline\?case=/)
  await expect(page.getByRole('heading', { name: 'Becha Account support application', level: 2 })).toBeVisible()
  await page.getByRole('link', { name: 'Banking Products', exact: true }).click()
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await page.screenshot({ path: 'test-results/enl-products-dark.png', animations: 'disabled' })
  await openBecha(page)
  await drawer.getByRole('tab', { name: 'Related Support' }).click()
  await drawer.getByRole('link', { name: /Account access assistance/ }).click()
  await expect(page.getByRole('region', { name: 'Support case details' })).toContainText('Account access assistance')
  await page.getByRole('link', { name: 'Banking Products', exact: true }).click()
  await page.getByRole('button', { name: 'View details: Nala Account', exact: true }).click()
  const nala = page.getByRole('dialog', { name: 'Nala Account' })
  await nala.getByRole('tab', { name: 'Related Support' }).click()
  await nala.getByRole('link', { name: /Nala enquiry/i }).click()
  await expect(page).toHaveURL(/\/tickets\?ticket=/)
  await page.getByRole('link', { name: 'Banking Products', exact: true }).click()
  await page.getByRole('button', { name: 'View details: Nala Account', exact: true }).click()
  await nala.getByRole('tab', { name: 'Related Support' }).click()
  await nala.getByRole('link', { name: /Card replacement dispute/i }).click()
  await expect(page).toHaveURL(/\/complaints\?case=/)
  await expect(page.getByRole('heading', { name: 'Card replacement dispute', level: 2 })).toBeVisible()
  await page.getByRole('link', { name: 'Banking Products', exact: true }).click()
  await openBecha(page)
  await drawer.getByRole('tab', { name: 'Related Support' }).click()
  await drawer.getByRole('link', { name: /personal banking/i }).click()
  await expect(page).toHaveURL(/\/knowledge\?article=/)
  await expect(page.getByRole('textbox', { name: 'Article title', exact: true })).toHaveValue(/Personal Banking/i)
  await page.getByRole('link', { name: 'Banking Products', exact: true }).click()
  await page.setViewportSize({ width: 900, height: 1000 })
  expect(await page.locator('.enl-product-grid').evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe(2)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.locator('.enl-product-grid').evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe(1)
  await openBecha(page)
  expect(await drawer.evaluate(el => el.getBoundingClientRect().width)).toBe(390)
  await page.screenshot({ path: 'test-results/enl-products-mobile.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(drawer).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'View details: Becha Account' })).toBeFocused()
  expect(errors).toEqual([])
})

test('administrator saves drafts for review and availability while agents see the reference catalogue', async ({ page }) => {
  await openHub(page)
  const qalo = await qaloSnapshot(page)
  await openBecha(page)
  const drawer = page.getByRole('dialog')
  await drawer.getByRole('button', { name: 'Edit Product', exact: true }).click()
  await drawer.getByRole('textbox', { name: 'Product display name' }).fill('Uncommitted edit')
  await expect(drawer.getByText('Unsaved changes', { exact: true })).toBeVisible()
  page.once('dialog', dialog => dialog.dismiss())
  await drawer.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(drawer.getByRole('textbox', { name: 'Product display name' })).toHaveValue('Uncommitted edit')
  page.once('dialog', dialog => dialog.accept())
  await drawer.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(drawer.getByRole('heading', { name: 'Becha Account', exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: 'Edit Product', exact: true }).click()
  await drawer.getByRole('textbox', { name: 'Product display name' }).fill('Becha draft for review')
  await drawer.getByRole('textbox', { name: 'Official product URL' }).fill('https://example.com/product')
  await drawer.getByRole('button', { name: 'Save Changes', exact: true }).click()
  await expect(drawer.getByRole('alert')).toContainText('official eNL domain')
  await drawer.getByRole('textbox', { name: 'Official product URL' }).fill('https://enlbank.co.za/becha')
  await drawer.getByRole('combobox', { name: 'Availability' }).selectOption('Temporarily Unavailable')
  await drawer.getByRole('combobox', { name: 'Product image' }).selectOption('Nala.png')
  await drawer.getByRole('button', { name: 'Add FAQ', exact: true }).click()
  const faq = drawer.getByRole('region', { name: 'FAQ 2' })
  await faq.getByRole('textbox', { name: 'Question' }).fill('How do I find the official page?')
  await faq.getByRole('textbox', { name: 'Answer' }).fill('Open the official product link.')
  await faq.getByRole('button', { name: 'Move up' }).click()
  await drawer.getByRole('region', { name: 'FAQ 2' }).getByRole('button', { name: 'Remove FAQ' }).click()
  await drawer.getByRole('button', { name: 'Save for review', exact: true }).click()
  await expect(drawer.getByRole('status')).toContainText('saved in this browser and marked for review')
  await expect(drawer.getByRole('heading', { name: 'Becha draft for review' })).toBeVisible()
  await page.reload()
  await expect(page.locator('.enl-product-card').filter({ has: page.getByRole('heading', { name: 'Becha Account', exact: true }) })).toContainText('Temporarily Unavailable')
  await openBecha(page)
  await drawer.getByRole('button', { name: 'Preview internal draft' }).click()
  await expect(drawer.locator('img')).toHaveAttribute('src', '/enl%20products/Nala.png')
  await drawer.getByRole('tab', { name: 'FAQs' }).click()
  await expect(drawer.getByText('How do I find the official page?', { exact: true })).toBeVisible()
  await expect(drawer.getByText('Where can I confirm the current product information?', { exact: true })).toHaveCount(0)
  expect(await qaloSnapshot(page)).toBe(qalo)

  await page.evaluate(() => sessionStorage.setItem('qalo-profile-preview', 'user:user-agent-2'))
  await page.reload()
  await openBecha(page)
  await expect(drawer.getByRole('button', { name: 'Edit Product' })).toHaveCount(0)
  await expect(drawer.getByRole('button', { name: 'Preview internal draft' })).toHaveCount(0)
  await drawer.getByRole('tab', { name: 'FAQs' }).click()
  await expect(drawer.getByText('How do I find the official page?', { exact: true })).toHaveCount(0)
  const denied = await page.evaluate(async workspace => {
    const modulePath = '/src/lib/bankingProductSupport.ts'
    const { saveBankingProduct } = await import(modulePath)
    try { await saveBankingProduct(workspace, 'user-agent-2', 'becha', undefined, {}); return '' }
    catch (error) { return (error as Error).message }
  }, bank)
  expect(denied).toContain('do not have permission')
})
