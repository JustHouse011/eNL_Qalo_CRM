async function openComplaints(page: Page) {
  await page.addInitScript(() => sessionStorage.setItem('qalo-profile-preview', 'Platform Super Admin'))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.goto('/overview')
  page.once('dialog', dialog => dialog.accept())
  await selectWorkspace(page, ENL_WORKSPACE_ID)
  await page.getByRole('link', { name: 'Complaints & Disputes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Complaints & Disputes', exact: true, level: 1 })).toBeVisible()
}
const queue = (page: Page) => page.getByRole('complementary', { name: 'Complaint queue' })
const detail = (page: Page) => page.getByRole('region', { name: 'Investigation workspace' })
const caseRow = (page: Page, subject: string) => queue(page).getByRole('button', { name: new RegExp(subject) })

test('complaints queue reconciles counts, filters, sorts, and opens linked records', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await openComplaints(page)
  await expect(queue(page).locator('.complaint-row')).toHaveCount(4)
  await expect(page.locator('.complaint-metric strong')).toHaveText(['1', '1', '1', '1'])
  await caseRow(page, 'Card replacement dispute').click()
  await expect(detail(page).getByRole('heading', { name: 'Card replacement dispute' })).toBeVisible()
  await expect(detail(page).getByText('Support case created.')).toBeVisible()
  await expect(detail(page).getByText('No original description is recorded', { exact: false })).toBeVisible()
  await page.screenshot({ path: 'test-results/enl-complaints-desktop.png', animations: 'disabled' })
  await detail(page).getByRole('tab', { name: 'Activity Timeline' }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(detail(page).getByRole('tab', { name: 'Notes' })).toHaveAttribute('aria-selected', 'true')
  await detail(page).getByRole('tab', { name: 'Documents' }).click()
  await expect(detail(page).getByText('No supporting documents are linked to this case.')).toBeVisible()
  await page.getByRole('button', { name: /^Open Investigations 1$/ }).click()
  await expect(queue(page).locator('.complaint-row')).toHaveCount(1)
  const search = queue(page).getByRole('textbox', { name: 'Search complaints' })
  await search.fill('Nala')
  await expect(queue(page).locator('.complaint-row')).toHaveCount(1)
  await search.fill('no matching case')
  await expect(queue(page).getByText('No matching complaints')).toBeVisible()
  await queue(page).getByRole('button', { name: 'Clear search' }).click()
  await page.getByRole('group', { name: 'Complaint status filters' }).getByRole('button', { name: 'All (4)', exact: true }).click()
  await queue(page).getByRole('button', { name: 'Filter complaints' }).click()
  const filter = page.getByRole('dialog', { name: 'Filter complaints' })
  await filter.getByRole('combobox', { name: 'Support category', exact: true }).selectOption('Card dispute')
  await filter.getByRole('combobox', { name: 'Priority', exact: true }).selectOption('normal')
  await filter.getByRole('button', { name: 'Apply filters' }).click()
  await expect(queue(page).locator('.complaint-row')).toHaveCount(1)
  await queue(page).getByRole('button', { name: 'Filter complaints' }).click()
  await filter.getByRole('button', { name: 'Reset filters' }).click()
  await queue(page).getByRole('combobox', { name: 'Sort complaints' }).selectOption('Highest priority')
  await expect(queue(page).locator('.complaint-row').first()).toContainText('Digital support escalation')
  await page.getByRole('combobox', { name: 'Department filter', exact: true }).selectOption({ label: 'Applications' })
  await expect(queue(page).locator('.complaint-row')).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Department filter', exact: true }).selectOption('')
  await caseRow(page, 'Card replacement dispute').click()
  await detail(page).getByRole('link', { name: 'Nala Account', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Nala Account' })).toBeVisible()
  await page.goBack()
  await detail(page).locator('.complaint-facts a').first().click()
  await expect(page).toHaveURL(/\/contacts\?customer=/)
  await page.goto('/complaints')
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await page.screenshot({ path: 'test-results/enl-complaints-dark.png', animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(queue(page)).toBeVisible()
  await expect(detail(page)).not.toBeVisible()
  await caseRow(page, 'Card replacement dispute').click()
  await expect(detail(page)).toBeVisible()
  await expect(queue(page)).not.toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/enl-complaints-mobile.png', animations: 'disabled' })
  await detail(page).getByRole('button', { name: 'Assign' }).click()
  await expect(page.getByRole('dialog', { name: 'Assign complaint' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await detail(page).getByRole('button', { name: 'Back to Complaints' }).click()
  await expect(queue(page)).toBeVisible()
  expect(errors).toEqual([])
})

test('complaint actions persist creation, assignment, escalation, status, and private updates', async ({ page }) => {
  test.setTimeout(120000)
  await openComplaints(page)
  const qalo = () => page.evaluate(() => JSON.stringify(JSON.parse(localStorage.getItem('qalo-workspaces-v2')!).snapshots['workspace-qalo']))
  const before = await qalo()
  await page.getByRole('button', { name: 'New Complaint', exact: true }).click()
  const modal = page.getByRole('dialog')
  await modal.getByRole('combobox', { name: 'Customer', exact: true }).selectOption({ index: 1 })
  await modal.getByRole('textbox', { name: 'Subject', exact: true }).fill('Customer follow-up complaint')
  await modal.getByRole('textbox', { name: 'Description', exact: true }).fill('Customer requested a callback about a service enquiry.')
  await modal.getByRole('button', { name: 'Save Complaint', exact: true }).click()
  await expect(detail(page).getByRole('heading', { name: 'Customer follow-up complaint' })).toBeVisible()
  await expect(page.locator('.complaint-metric strong').first()).toHaveText('2')
  await expect(detail(page).getByText('Customer requested a callback about a service enquiry.')).toBeVisible()
  await detail(page).getByRole('button', { name: 'Internal Note', exact: true }).click()
  await detail(page).getByRole('textbox', { name: 'Internal note', exact: true }).fill('Confirm the support handover with the team.')
  await detail(page).getByRole('button', { name: 'Assign', exact: true }).click()
  const agent = modal.getByRole('combobox', { name: 'Assigned agent', exact: true })
  await agent.selectOption({ index: 1 })
  const assignedName = await agent.locator('option:checked').textContent()
  await modal.getByRole('button', { name: 'Save Assignment' }).click()
  await expect(detail(page).locator('.complaint-facts')).toContainText(assignedName!)
  await expect(detail(page).getByRole('textbox', { name: 'Internal note', exact: true })).toHaveValue('Confirm the support handover with the team.')
  await detail(page).getByRole('button', { name: 'Save Note' }).click()
  await expect(detail(page).getByRole('status')).toContainText('Internal note saved.')
  await detail(page).getByRole('tab', { name: 'Notes (1)', exact: true }).click()
  await expect(detail(page).getByRole('tabpanel')).toContainText('Confirm the support handover with the team.')
  await detail(page).getByRole('button', { name: 'Add Update', exact: true }).click()
  await detail(page).getByRole('textbox', { name: 'Staff case update' }).fill('Staff reviewed the case details.')
  await detail(page).getByRole('button', { name: 'Save Update' }).click()
  await expect(detail(page).getByRole('status')).toContainText('Staff update saved to the case.')
  await detail(page).getByRole('tab', { name: 'Escalation', exact: true }).click()
  await detail(page).getByRole('button', { name: 'Escalate complaint' }).click()
  await modal.getByRole('textbox', { name: 'Escalation reason' }).fill('The review requires a supervisor decision.')
  await modal.getByRole('button', { name: 'Record Escalation' }).click()
  await expect(detail(page).getByRole('tabpanel')).toContainText('The review requires a supervisor decision.')
  await detail(page).getByRole('button', { name: 'Update Status' }).click()
  await modal.getByRole('combobox', { name: 'Case status' }).selectOption('Resolved Cases')
  await modal.getByRole('combobox', { name: 'Case priority' }).selectOption('high')
  await modal.getByRole('button', { name: 'Save Status' }).click()
  await expect(page.locator('.complaint-metric strong').last()).toHaveText('2')
  await page.reload()
  await expect(detail(page).getByRole('heading', { name: 'Customer follow-up complaint' })).toBeVisible()
  await expect(detail(page).locator('.complaint-priority')).toHaveText('high')
  await expect(detail(page).getByRole('tabpanel')).toContainText('Staff reviewed the case details.')
  await expect(detail(page).getByRole('tabpanel')).toContainText('Complaint resolved')
  expect(await qalo()).toBe(before)
})

test('complaint command rejects foreign agents, cross-department moves, invalid status and stale actions', async () => {
  const values = new Map<string, string>()
  const service = createSupportService(() => ({ getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) }))
  service.initializeEnl(platformPreview.id)
  const complaints = createComplaintSupport(service)
  const snapshot = await service.readWorkspace(ENL_WORKSPACE_ID)
  const record = snapshot.bankingCases!.find(c => c.kind === 'complaint')!
  const revision = record.history.at(-1)?.id
  const foreignAgent = (await service.readWorkspace(QALO_WORKSPACE_ID)).agents[0].id
  const departmentId = snapshot.departments.find(d => d.id !== record.departmentId)!.id
  await expect(complaints.change(ENL_WORKSPACE_ID, platformPreview.id, record.id, { kind: 'assignment', revision, departmentId: record.departmentId, agentId: foreignAgent })).rejects.toThrow('ineligible')
  await expect(complaints.change(ENL_WORKSPACE_ID, 'user-enl-agent-demo', record.id, { kind: 'assignment', revision, departmentId, agentId: null })).rejects.toThrow('support manager')
  await expect(complaints.change(ENL_WORKSPACE_ID, platformPreview.id, record.id, { kind: 'status', revision, status: 'Closed', priority: 'normal', reason: '' })).rejects.toThrow('valid complaint status')
  await expect(complaints.change(QALO_WORKSPACE_ID, platformPreview.id, record.id, { kind: 'note', text: 'Attempt to cross workspace scope.' })).rejects.toThrow('cannot manage complaints')
  await complaints.change(ENL_WORKSPACE_ID, platformPreview.id, record.id, { kind: 'note', text: 'Review the support request.' })
  await expect(complaints.change(ENL_WORKSPACE_ID, platformPreview.id, record.id, { kind: 'status', revision, status: 'Resolved Cases', priority: 'normal', reason: '' })).rejects.toThrow('This case changed')
})
