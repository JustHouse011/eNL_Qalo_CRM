  await page.keyboard.press('Escape')
  await page.locator('[data-directory-search]').fill('Directory Organisation')
  const trigger = page.getByRole('button', { name: 'View Directory Organisation', exact: true })
  await trigger.click()
  await page.getByRole('button', { name: 'Edit organisation', exact: true }).click()
  await page.getByLabel('Internal reference').fill('QA-REF-1')
  await page.getByRole('button', { name: 'Save organisation', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('status')).toContainText('Organisation saved')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('QA-REF-1')
  const overview = page.getByRole('tab', { name: 'Overview', exact: true })
  await overview.focus(); await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: /^Activity/ })).toBeFocused()
  await expect(page.getByRole('dialog')).toContainText('No recorded activity')
  await page.keyboard.press('Escape'); await expect(trigger).toBeFocused()
  await trigger.click(); await page.goBack()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await trigger.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  const content = (await page.locator('.crm-directory').boundingBox())!
  await page.mouse.click(content.x + content.width - 15, content.y + 100)
