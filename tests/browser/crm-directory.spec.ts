test('both workspace directories, source relations, themes and bounded left flyout', async ({ page }) => {
  test.setTimeout(180000)
  page.on('dialog', dialog => dialog.accept())
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/contacts', { waitUntil: 'domcontentloaded' })
  await expect(page.locator('.crm-record-table tbody tr').first()).toBeVisible()
  mkdirSync('test-results', { recursive: true })
  for (const bank of [false, true]) {
    if (bank) await selectWorkspace(page, ENL_WORKSPACE_ID)
    await page.locator('[data-directory-search]').fill(bank ? 'Amara Mabasa' : 'Naledi Mokone')
    const row = page.locator('.crm-record-table tbody tr').first()
    await expect(row).toContainText(bank ? 'Amara' : 'Naledi')
    await row.getByRole('button', { name: /^View / }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    const bounds = (await dialog.boundingBox())!, content = (await page.locator('.crm-directory').boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(content.x - 1)
    expect(bounds.x).toBeLessThan(content.x + 2)
    expect(bounds.width).toBeGreaterThanOrEqual(460)
    expect(bounds.width).toBeLessThanOrEqual(560)
    await dialog.getByRole('tab', { name: 'Activity' }).click()
    await expect(dialog.getByText('Conversation opened', { exact: true })).toBeVisible()
    await dialog.getByRole('tab', { name: 'Related Records' }).click()
    await expect(dialog.locator('a[href^="/inbox?"]')).toHaveCount(1)
    await dialog.getByRole('tab', { name: 'Overview', exact: true }).click()
    await dialog.getByRole('button', { name: bank ? 'Metsi Enterprise' : 'Ikhaya Community Co-operative' }).click()
    await expect(page.getByRole('dialog', { name: 'Organisation details' })).toBeVisible()
    await expect(page.locator('.crm-linked-person')).toHaveCount(6)
    for (const mode of ['light', 'dark']) {
      const switcher = page.getByRole('button', { name: `Switch to ${mode} theme`, exact: true })
      if (await switcher.count()) await switcher.click()
      await page.screenshot({ path: `test-results/crm-directory-${bank ? 'enl' : 'qalo'}-${mode}.png`, animations: 'disabled' })
    }
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await page.locator('[data-directory-search]').fill('')
    await page.getByRole('tab', { name: 'Interaction History' }).click()
    await expect(page.locator('.crm-record-table tbody tr').first()).toBeVisible()
    await page.getByRole('tab', { name: bank ? 'Customer Directory' : 'Contact Directory', exact: true }).click()
  }
  expect(errors).toEqual([])
})

