test('directory relations, validation, pagination and additive fixtures preserve source records', () => {
  const source = structuredClone(initialDemoData)
  const next = addDirectoryFixtures(source, 'test', false, [], [], Date.parse('2026-11-06T10:00:00Z'))
  expect(next.contacts).toHaveLength(source.contacts.length + 18)
  expect(next.contacts.slice(0, source.contacts.length)).toEqual(source.contacts)
  expect(addDirectoryFixtures(next, 'test', false, [], [], 0)).toBe(next)
  const people = directoryRows(next, 'contacts', 'test')
  const person = people.find(r => r.id === 'test:directory:person:0')!
  expect(person.conversations).toHaveLength(1)
  expect(directoryEvents(person)).toHaveLength(1)
  expect(people.find(r => r.id === 'test:directory:person:17')!.lastInteraction).toBeNull()
  const companies = directoryRows(next, 'organisations', 'test')
  expect(companies.find(r => r.id === 'test:directory:organisation:0')!.people).toHaveLength(6)
  expect(directoryRows({ ...next, workspaceId: 'other' }, 'contacts', 'test')).toEqual([])
  expect(() => validatePerson({ ...next.contacts[0], id: 'new', email: next.contacts[0].email.toUpperCase() }, next)).toThrow(/another contact/)
  expect(() => parseDirectoryCsv('name,email,organisation\nA,a@example.invalid,X\nB,A@example.invalid,Y', next)).toThrow(/Duplicate/)
  expect(parseDirectoryCsv('name,email,organisation\nA,a@example.invalid,X', next)).toHaveLength(1)
  const result = filterDirectory(people, { search: '', type: 'all', status: 'all', scope: 'all', banking: false, from: '', to: '', sort: 'name', page: 999, pageSize: 10 })
  expect(result.page).toBe(result.pages)
  expect(result.rows.length).toBeLessThanOrEqual(10)
})

