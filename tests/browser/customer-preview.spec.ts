import { test, expect } from '@playwright/test'

test('floating support lifecycle, keyboard access and local inbox', async ({ page, context }) => {
  test.setTimeout(120000)
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:5187')) failures.push(request.url()) })
  await page.goto('/customer-preview')
  const launcher = page.getByRole('button', { name: 'Open support chat', exact: true })
  await expect(page.getByRole('region', { name: 'Qalo Ya Afrika Support' })).toHaveCount(0)
  const before = await launcher.boundingBox()
  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
  expect((await launcher.boundingBox())?.y).toBe(before?.y)
  await launcher.focus(); await page.keyboard.press('Enter')
  const panel = page.getByRole('region', { name: 'Qalo Ya Afrika Support' })
  await expect(panel).toBeFocused()
  await page.getByRole('button', { name: 'Qalo Store', exact: true }).click()
  const draft = page.getByRole('textbox', { name: 'Your message' })
  await expect(draft).toBeFocused()
  await draft.fill('Where is my parcel?')
  await page.keyboard.press('Escape')
  await expect(launcher).toBeFocused()
  await launcher.click()
  await expect(draft).toHaveValue('Where is my parcel?')
  await page.clock.install({ time: new Date('2026-09-30T10:00:00Z') })
  await page.clock.pauseAt(new Date('2026-09-30T10:00:01Z'))
  await draft.press('Enter')
  await draft.press('Enter')
  await expect(page.getByText('Qalo Support is typing')).toBeVisible()
  await panel.getByRole('button', { name: 'Minimise support chat' }).click()
  await page.clock.fastForward(1300)
  await expect(page.getByLabel('1 unread messages', { exact: true })).toBeVisible()
  await launcher.click()
  await expect(panel.getByText('Where is my parcel?', { exact: true })).toHaveCount(1)
  await expect(panel.getByText(/I can help with orders/)).toBeVisible()
  await page.clock.resume()
  const agent = await context.newPage()
  await agent.goto('/inbox')
  await agent.getByRole('button', { name: /Website Visitor/ }).click()
  await expect(agent.getByText('Where is my parcel?', { exact: true })).toBeVisible()
  await agent.getByLabel('Write a customer reply').fill('Your parcel enquiry is being reviewed.')
  await agent.getByRole('button', { name: 'Send reply', exact: true }).click()
  await expect(panel.getByText('Your parcel enquiry is being reviewed.')).toBeVisible()
  await page.getByRole('button', { name: 'End conversation', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Keep chatting' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'End conversation', exact: true })).toBeFocused()
  await expect(draft).toBeEnabled()
  await page.getByRole('button', { name: 'End conversation', exact: true }).click()
  await page.getByRole('button', { name: 'Yes, end conversation' }).click()
  await expect(draft).toBeDisabled()
  await expect(page.getByText('Conversation ended', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Rate 5 out of 5' }).click()
  await expect(page.getByText('Thank you for your feedback.')).toBeVisible()
  await page.getByRole('button', { name: 'Start new conversation' }).click()
  await expect(panel.getByText('Where is my parcel?', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Community Investment', exact: true })).toBeVisible()
  await expect(draft).toHaveValue('')
  expect(failures).toEqual([])
})

test('mobile fit, multiline composition, confirmation focus and pending reply cancellation', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 667 })
  await page.goto('/customer-preview')
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await expect(page.getByRole('navigation')).toBeVisible()
  await page.getByRole('navigation').getByRole('link', { name: 'About', exact: true }).click()
  await page.getByRole('button', { name: 'Open support chat' }).click()
  const panel = page.getByRole('region', { name: 'Qalo Ya Afrika Support' })
  const box = (await panel.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0); expect(box.y).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(375)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(375)
  await page.getByRole('button', { name: 'General & Technical Support' }).click()
  const draft = page.getByRole('textbox', { name: 'Your message' })
  await draft.fill('Account access'); await draft.press('Shift+Enter'); await draft.press('a')
  await expect(draft).toHaveValue('Account access\na')
  await page.getByRole('button', { name: 'Send message' }).click()
  await page.getByRole('button', { name: 'End conversation', exact: true }).click()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Yes, end conversation' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Keep chatting' })).toBeFocused()
  await page.getByRole('button', { name: 'Yes, end conversation' }).click()
  await page.getByRole('button', { name: 'Start new conversation' }).click()
  await page.waitForTimeout(1500)
  await expect(panel.getByText(/Let’s work through this together/)).toHaveCount(0)
  await page.setViewportSize({ width: 375, height: 390 })
  const small = (await panel.boundingBox())!
  expect(small.y).toBeGreaterThanOrEqual(0)
  await expect(draft).toBeInViewport()
})
