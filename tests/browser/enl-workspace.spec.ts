function fixture(legacy?: string) {
  const values = new Map<string, string>(legacy ? [[LEGACY_STORAGE_KEY, legacy]] : [])
  const service = createSupportService(() => ({ getItem: key => values.get(key) ?? null, setItem: (key, value) => { values.set(key, value) } }))
  return { service, values }
}
async function chooseProfile(page: Page, role: string) {
  const previous = page.url()
  const id = ({ Admin: 'user-agent-1', Supervisor: 'user-agent-2', Agent: 'user-agent-3', 'Platform Super Admin': 'user-agent-1' } as Record<string, string>)[role] || role.replace('user:', '')
  await page.goto('/dev/session')
  await page.getByLabel('Preview identity').selectOption(id)
  await page.getByRole('button', { name: 'Start mock session' }).click()
  await page.goto(previous)
}
async function openEnl(page: Page) {
  await page.goto('/workspaces')
  await chooseProfile(page, 'Platform Super Admin')
  page.on('dialog', d => d.accept())
  await selectWorkspace(page, ENL_WORKSPACE_ID)
}
test('eNL initialization is stable, atomic, idempotent and preserves modified Qalo and backups', async () => {
  const original = createMockData(); original.contacts[0].name = 'Preserved edited Qalo contact'
  const raw = JSON.stringify(original)
  const { service, values } = fixture(raw)
  const before = await service.readWorkspace(QALO_WORKSPACE_ID)
  expect(() => service.initializeEnl('user-agent-3')).toThrow('Platform')
  expect(service.initializeEnl(platformPreview.id)).toBe(ENL_WORKSPACE_ID)
  const store = service.registry()
  expect(store.workspaces.find(w => w.id === ENL_WORKSPACE_ID)).toMatchObject({ name: 'eNL Mutual Bank', slug: 'enl-mutual-bank', supportMode: 'banking', primaryColor: '#652D8D', tagline: 'Banking you for a purpose' })
  expect(store.snapshots[ENL_WORKSPACE_ID].conversations).toHaveLength(10)
  expect(store.snapshots[ENL_WORKSPACE_ID].tickets).toHaveLength(6)
  expect(store.snapshots[ENL_WORKSPACE_ID].departments.map(d => d.name)).toEqual(expect.arrayContaining(bankingDepartments))
  expect(store.snapshots[ENL_WORKSPACE_ID].articles.every(a => !a.published && /review/i.test(a.review || ''))).toBe(true)
  expect(store.snapshots[ENL_WORKSPACE_ID].contacts.every(c => c.name.startsWith('Demo ') && c.email.endsWith('@example.invalid'))).toBe(true)
  expect(await service.readWorkspace(QALO_WORKSPACE_ID)).toEqual(before)
  expect(values.get(LEGACY_STORAGE_KEY)).toBe(raw); expect(values.get(WORKSPACE_BACKUP_KEY)).toBe(raw)
  await service.updateWorkspace(ENL_WORKSPACE_ID, d => ({ ...d, assistant: { ...d.assistant!, persona: 'Edited persona retained' } }))
  const edited = service.registry()
  service.initializeEnl(platformPreview.id)
  expect(service.registry()).toEqual(edited)
  expect(store.snapshots[ENL_WORKSPACE_ID].conversations.every(c => c.workspaceId === ENL_WORKSPACE_ID && c.messages.every(m => m.workspaceId === ENL_WORKSPACE_ID && m.conversationId === c.id))).toBe(true)
})
test('banking widget commands, manual takeover and offline tickets stay workspace-bound', async () => {
  const { service } = fixture(); service.initializeEnl(platformPreview.id)
  const bank = createBankingSupport(service)
  const before = await service.readWorkspace(QALO_WORKSPACE_ID)
  const id = await bank.start(ENL_WORKSPACE_ID, 'Fictional Visitor', 'visitor@example.invalid', 'A general question about mobile navigation')
  await bank.send(ENL_WORKSPACE_ID, id, 'What are the Becha fees?')
  expect((await service.readWorkspace(ENL_WORKSPACE_ID)).conversations.find(c => c.id === id)?.messages.at(-1)?.text).toContain('require approved source')
  await bank.requestHuman(ENL_WORKSPACE_ID, id)
  expect((await service.readWorkspace(ENL_WORKSPACE_ID)).conversations.find(c => c.id === id)?.handling).toBe('waiting')
  await expect(bank.takeover(ENL_WORKSPACE_ID, id, 'user-agent-3')).rejects.toThrow('membership')
  await bank.takeover(ENL_WORKSPACE_ID, id, 'user-enl-agent-demo')
  expect((await service.readWorkspace(ENL_WORKSPACE_ID)).conversations.find(c => c.id === id)).toMatchObject({ handling: 'human', assignee: 'Demo Zanele Mokoena' })
  const count = (await service.readWorkspace(ENL_WORKSPACE_ID)).conversations.find(c => c.id === id)!.messages.length
  await bank.send(ENL_WORKSPACE_ID, id, 'Please follow up')
  expect((await service.readWorkspace(ENL_WORKSPACE_ID)).conversations.find(c => c.id === id)!.messages).toHaveLength(count + 1)
  await bank.start(ENL_WORKSPACE_ID, 'Offline Visitor', 'offline@example.invalid', 'Please record an offline request', true)
  expect((await service.readWorkspace(ENL_WORKSPACE_ID)).tickets).toHaveLength(7)
  await expect(bank.send(QALO_WORKSPACE_ID, id, 'Cannot cross workspaces')).rejects.toThrow('unavailable')
  expect(await service.readWorkspace(QALO_WORKSPACE_ID)).toEqual(before)
})
test('assistant safety, fraud escalation, memberships and disable remain local', async () => {
  const { service } = fixture(); service.initializeEnl(platformPreview.id)
  const bank = createBankingSupport(service)
  const data = await service.readWorkspace(ENL_WORKSPACE_ID)
  for (const text of ['My PIN is 1234', 'Card 1234 5678 1234 5678']) expect(() => validateBankingMessage(text)).toThrow('Remove credentials')
  expect(bankingReply('Can you transfer my balance?', data)).toContain('cannot access balances')
  expect(bankingReply('What is the interest rate?', data)).toContain('require approved source')
  const id = await bank.start(ENL_WORKSPACE_ID, 'Fraud Demo', 'fraud@example.invalid', 'I suspect fraud in a fictional scenario')
  expect((await service.readWorkspace(ENL_WORKSPACE_ID)).conversations.find(c => c.id === id)).toMatchObject({ handling: 'waiting', department: 'Fraud and Security', priority: 'urgent' })
  await service.updateWorkspace(ENL_WORKSPACE_ID, d => ({ ...d, assistant: { ...d.assistant!, enabled: false } }))
  expect(bankingReply('Hello', await service.readWorkspace(ENL_WORKSPACE_ID))).toContain('disabled')
  const store = service.registry()
  expect(canInWorkspace(store.users.find(u => u.id === 'user-agent-3'), store.workspaces.find(w => w.id === ENL_WORKSPACE_ID), store.memberships, 'view')).toBe(false)
  expect(canInWorkspace(store.users.find(u => u.id === 'user-enl-agent-demo'), store.workspaces.find(w => w.id === ENL_WORKSPACE_ID), store.memberships, 'reply')).toBe(true)
})
