import { selectWorkspace } from '../helpers/workspaceSelector'
import { test, expect, type Page } from '@playwright/test'
async function preview(page: Page, id: string) {
  await page.goto('/dev/session')
  await page.getByRole('combobox', { name: 'Account', exact: true }).selectOption(id)
  await page.getByRole('button', { name: 'Start session' }).click()
  await expect(page.getByRole('link', { name: 'Overview', exact: true })).toBeVisible()
}
for (const [id, name, count, admin] of [
  ['user-agent-1', 'Bongani Nombamba', 2, true],
  ['user-agent-2', 'Phindile Khumalo', 2, false],
  ['user-agent-3', 'Tumo Likotsi', 2, false],
] as const) {
  test(`${name}: identity, memberships and profile routes`, async ({ page }) => {
    await preview(page, id)
    await expect(page.locator('.workspace-select-menu [role=option]')).toHaveCount(count)
    await page.getByRole('button', { name: 'Profile menu', exact: true }).click()
    await expect(page.getByLabel('Switch account')).toHaveCount(0)
    await expect(page.locator('.profile-popover')).toContainText(name)
    await expect(page.getByRole('button', { name: 'Platform Administration', exact: true })).toHaveCount(admin ? 1 : 0)
    await page.getByRole('button', { name: 'My Profile', exact: true }).click()
    await expect(page.getByLabel('Display name', { exact: true })).toHaveValue(name)
    await page.getByRole('link', { name: 'My Access', exact: true }).click()
    await expect(page.locator('.identity-table tbody tr')).toHaveCount(count)
    await expect(page.locator('.identity-table')).toContainText(admin ? 'Supervisor' : 'Support Agent')
    await page.goto('/platform')
    await expect(page.getByRole('heading', { name: admin ? 'Platform Administration' : 'Access unavailable', exact: true })).toBeVisible()
    if (!admin) await expect(page.getByRole('button', { name: 'Invite User', exact: true })).toHaveCount(0)
  })
}
test('workspace context, transient reset and responsive profile', async ({ page }) => {
  await preview(page, 'user-agent-1')
  await page.goto('/inbox?conversation=conv-1')
  await page.getByLabel('Write a customer reply').fill('Unsent Qalo draft')
  page.on('dialog', d => d.accept())
  const selector = page.locator('.workspace-select-menu')
  const enl = await selector.locator('[role=option]').evaluateAll(options => options.map(o => ({ id: o.getAttribute('data-workspace-id')!, text: o.textContent })).find(o => /eNL/.test(o.text || ''))!.id)
  await selectWorkspace(page, enl)
  await expect(page.getByRole('link', { name: 'Accounts & Transactions', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Orders & products', exact: true })).toHaveCount(0)
  await selectWorkspace(page, 'workspace-qalo')
  await expect(page.getByLabel('Write a customer reply')).toBeEmpty()
  await expect(page.getByRole('link', { name: 'Accounts & Transactions', exact: true })).toHaveCount(0)
  await page.goto('/account/profile')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByLabel('Display name', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
test('invitation review saves locally without creating users or sending mail; sign out persists', async ({ page }) => {
  await preview(page, 'user-agent-1')
  await page.goto('/platform')
  await page.getByRole('button', { name: 'Invite User', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Fictional colleague')
  await page.getByLabel('Email', { exact: true }).fill('colleague@example.invalid')
  await page.getByRole('checkbox').first().check()
  await page.getByRole('button', { name: 'Review invitation', exact: true }).click()
  await page.getByRole('button', { name: 'Save local draft', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('No email sent')
  await page.getByRole('button', { name: 'Audit History', exact: true }).click()
  await expect(page.locator('.identity-card')).toContainText('Fictional colleague')
  await page.getByRole('button', { name: 'Profile menu', exact: true }).click()
  await page.getByRole('button', { name: 'Sign Out', exact: true }).click()
  await page.goto('/account/profile')
  await expect(page).toHaveURL(/signin/)
})

test('personal profile and preferences stay with their mock user; security stays unavailable', async ({ page }) => {
  await preview(page, 'user-agent-1')
  await page.goto('/account/profile')
  await page.getByLabel('Display name', { exact: true }).fill('Bongani Preview')
  await page.getByRole('button', { name: 'Save profile', exact: true }).click()
  await expect(page.locator('.agent-mini-copy')).toContainText('Bongani Preview')
  await page.getByRole('link', { name: 'Preferences', exact: true }).click()
  await page.getByLabel('Reduced motion', { exact: true }).check()
  await page.getByLabel('In-app notifications', { exact: true }).uncheck()
  await expect(page.locator('html')).toHaveClass(/identity-reduced-motion/)
  await expect(page.getByLabel('Language', { exact: true })).toBeDisabled()
  await page.getByRole('link', { name: 'Security', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pending authentication integration' })).toHaveCount(4)
  await preview(page, 'user-agent-2')
  await page.goto('/account/profile')
  await expect(page.getByLabel('Display name', { exact: true })).toHaveValue('Phindile Khumalo')
  await expect(page.locator('html')).not.toHaveClass(/identity-reduced-motion/)
  await preview(page, 'user-agent-1')
  await page.goto('/account/profile')
  await expect(page.getByLabel('Display name', { exact: true })).toHaveValue('Bongani Preview')
  await expect(page.locator('html')).toHaveClass(/identity-reduced-motion/)
})
