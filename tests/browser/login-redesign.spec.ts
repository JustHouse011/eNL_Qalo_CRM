import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'

test.beforeEach(async ({ page }) => { page.setDefaultNavigationTimeout(90000); await page.emulateMedia({ reducedMotion: 'reduce' }) })

for (const [brand, name, workspace] of [['qalo', 'Qalo Ya Afrika', 'workspace-qalo'], ['enl', 'eNL Mutual Bank', 'workspace-enl-mutual-bank']] as const) {
  test(`${brand}: reference layout, imagery, responsive masks and reduced motion`, async ({ page }) => {
    test.setTimeout(120000)
    const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
    await page.setViewportSize({ width: 1083, height: 768 })
    await page.goto(`/${brand}/signin`, { waitUntil: 'domcontentloaded' })
    await expect(page.getByRole('heading', { name: 'Welcome back.', exact: true })).toBeVisible()
    await expect(page.getByRole('img', { name, exact: true })).toBeVisible()
    await expect(page.locator('.login-backdrop,.demo-login')).toHaveCount(0)
    await expect(page.getByRole('link', { name: /Switch account|Create account|Google|Facebook/i })).toHaveCount(0)
    await expect(page.locator('.login-form input')).toHaveCount(2)
    await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'password')
    await page.getByRole('button', { name: 'Show password', exact: true }).click()
    await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text')
    await page.getByRole('button', { name: 'Hide password', exact: true }).click()
    for (const img of await page.locator('.login-shell img').all()) await expect.poll(() => img.evaluate(img => (img as HTMLImageElement).complete && (img as HTMLImageElement).naturalWidth > 0)).toBe(true)
    const shell = (await page.locator('.login-shell').boundingBox())!, artwork = (await page.locator('.login-artwork').boundingBox())!
    expect(shell.width / 1083).toBeCloseTo(.84, 1); expect(artwork.width / (shell.width - 18)).toBeCloseTo(.6, 1)
    expect(await page.locator('.mosaic-circle-top').evaluate(el => getComputedStyle(el).animationName)).toBe('none')
    mkdirSync('test-results', { recursive: true })
    await page.screenshot({ path: `test-results/login-${brand}-reference.png`, animations: 'disabled' })
    for (const width of [1440, 820, 390]) {
      await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await expect(page.getByRole('button', { name: 'Sign In', exact: true })).toBeVisible()
      await page.screenshot({ path: `test-results/login-${brand}-${width}.png`, animations: 'disabled' })
    }
    expect(errors).toEqual([])
  })

  test(`${brand}: existing credentials, OTP, workspace landing, logout and protected-route guards`, async ({ page }) => {
    test.setTimeout(120000)
    await page.goto(`/${brand}/signin`, { waitUntil: 'domcontentloaded' })
    await page.getByLabel('Email address', { exact: true }).fill('wrong@example.invalid')
    await page.getByLabel('Password', { exact: true }).fill('incorrect-password')
    await page.getByRole('button', { name: 'Sign In', exact: true }).click()
    await expect(page.getByRole('alert')).toHaveText('Email or password is incorrect.')
    await page.getByLabel('Email address', { exact: true }).fill('bongani.nombamba@enlbank.co.za')
    await page.getByLabel('Password', { exact: true }).fill('12345678')
    await page.getByRole('button', { name: 'Sign In', exact: true }).click()
    let code = await page.getByTestId('email-preview-code').innerText()
    await page.getByRole('textbox', { name: 'One-time code' }).fill(code === '111111' ? '222222' : '111111')
    await page.getByRole('button', { name: 'Verify code', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('incorrect')
    await page.getByRole('button', { name: 'Resend code', exact: true }).click()
    expect(await page.getByTestId('email-preview-code').innerText()).not.toBe(code)
    code = await page.getByTestId('email-preview-code').innerText()
    await page.getByRole('textbox', { name: 'One-time code' }).fill(code)
    await page.getByRole('button', { name: 'Verify code', exact: true }).click()
    await expect(page).toHaveURL(/\/overview$/)
    await expect(page.getByRole('combobox', { name: 'Switch workspace', exact: true })).toHaveAttribute('data-workspace-id', workspace)
    await expect(page.locator('.dashboard-kpi')).toHaveCount(4)
    await expect(page.locator('.dashboard-extra')).toHaveCount(0)
    await page.getByRole('link', { name: 'Inbox', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Shared inbox', exact: true })).toBeVisible()
    await expect(page.locator('.conversation-row').first()).toBeVisible()
    await page.getByRole('button', { name: 'Log Out', exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`/${brand}/signin$`))
    await page.reload({ waitUntil: 'domcontentloaded' })
    await expect(page.getByRole('heading', { name: 'Welcome back.', exact: true })).toBeVisible()
    await page.goto('/inbox', { waitUntil: 'domcontentloaded' })
    await expect(page).toHaveURL(new RegExp(`/${brand}/signin$`))
    await expect(page.locator('.sidebar')).toHaveCount(0)
  })
}

test('legacy sign-in follows workspace context and unauthorised staff cannot select eNL by URL', async ({ page }) => {
  test.setTimeout(120000)
  await page.goto('/signin?workspace=workspace-enl-mutual-bank', { waitUntil: 'domcontentloaded' })
  await expect(page).toHaveURL(/\/enl\/signin$/)
  if (process.env.QALO_PREVIEW === '1') return
  await page.evaluate(() => { sessionStorage.setItem('qalo-developer-user', 'user:user-agent-3'); sessionStorage.setItem('qalo-profile-preview', 'signed-out') })
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByLabel('Email address', { exact: true }).fill('bongani.nombamba@enlbank.co.za')
  await page.getByLabel('Password', { exact: true }).fill('12345678')
  await page.getByRole('button', { name: 'Sign In', exact: true }).click()
  await page.getByRole('textbox', { name: 'One-time code' }).fill(await page.getByTestId('email-preview-code').innerText())
  await page.getByRole('button', { name: 'Verify code', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('cannot open the selected workspace')
  await expect(page).toHaveURL(/\/enl\/signin$/)
  await page.goto('/inbox', { waitUntil: 'domcontentloaded' })
  await expect(page.locator('.sidebar')).toHaveCount(0)
})

test('normal motion remains subtle and does not interrupt typing or validation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/enl/signin', { waitUntil: 'domcontentloaded' })
  await expect(page.locator('.mosaic-circle-top')).toHaveCSS('animation-duration', '1s, 19s')
  await expect(page.locator('.mosaic-orbit')).toHaveCSS('animation-duration', '48s')
  await page.getByLabel('Email address', { exact: true }).fill('motion@example.invalid')
  await page.getByLabel('Password', { exact: true }).fill('typing-remains-stable')
  await expect(page.getByLabel('Email address', { exact: true })).toHaveValue('motion@example.invalid')
  await page.getByRole('button', { name: 'Sign In', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Email or password is incorrect.')
})
