import { test, expect } from '@playwright/test'

test('profile access and integration workflows remain local and distinguish saved configuration from connection state', async ({ page, baseURL }) => {
  const external: string[] = []
  page.on('request', request => { if (!request.url().startsWith('data:') && new URL(request.url()).origin !== new URL(baseURL!).origin) external.push(request.url()); if (request.url().includes('/api/')) external.push(request.url()) })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  await page.getByLabel('Email address').fill('bongani.nombamba@enlbank.co.za')
  await page.getByLabel('Password', { exact: true }).fill('12345678')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Check your code' })).toBeVisible()
  const localCode = await page.getByTestId('email-preview-code').textContent()
  await page.getByLabel('One-time code').fill(localCode!.trim())
  await page.getByRole('button', { name: 'Verify code' }).click()
  await page.goto('/dev/session')
  await page.getByLabel('Preview identity').selectOption('user-agent-3')
  await page.getByRole('button', { name: 'Start mock session' }).click()
  await expect(page.getByRole('link', { name: 'Integrations', exact: true })).toHaveCount(0)
  await page.goto('/integrations')
  await expect(page.getByRole('heading', { name: 'Access unavailable' })).toBeVisible()
  await page.goto('/dev/session')
  await page.getByLabel('Preview identity').selectOption('user-agent-1')
  await page.getByRole('button', { name: 'Start mock session' }).click()
  await page.getByRole('link', { name: 'Integrations', exact: true }).click()
  await page.getByRole('button', { name: 'Configure channel', exact: true }).nth(1).click()
  await page.getByLabel('Display name').fill('Customer care email')
  await page.getByLabel('Account or page reference').fill('q1')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('at least 4 characters')
  await page.getByLabel('Account or page reference').fill('qalo-customer-care')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Changes saved')
  await expect(page.getByText('Configuration saved', { exact: true })).toBeVisible()
  await expect(page.getByText('Connection not verified', { exact: true })).toBeVisible()
  await expect(page.getByText('Connected', { exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByText('qalo-customer-care')).toBeVisible()
  await page.getByRole('link', { name: 'AI Assist', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Preview' })).toBeVisible()
  await page.getByLabel('Community Investment instructions').fill('Always acknowledge the community application question and hand off for review.')
  await expect(page.locator('.ai-response-preview')).toContainText('Always acknowledge the community application question')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Changes saved')
  await page.reload()
  await page.getByRole('link', { name: 'AI Assist', exact: true }).click()
  await expect(page.getByLabel('Community Investment instructions')).toHaveValue('Always acknowledge the community application question and hand off for review.')
  await expect(page.locator('.ai-response-preview')).toContainText('Always acknowledge the community application question')
  await page.getByRole('link', { name: 'Orders & products', exact: true }).click()
  await page.getByLabel('Search orders').fill('ORDER-1')
  await page.getByRole('button', { name: 'Request refund review' }).click()
  await expect(page.getByRole('status')).toContainText('Review requested for ORDER-1')
  await expect(page.getByText('Payment: Awaiting verification')).toBeVisible()
  await expect(page.getByText('Refund / exchange request: Review requested')).toBeVisible()
  expect(external).toEqual([])
})

test('transfer, reply, attachment reference and derived reporting', async ({ page }) => {
  await page.goto('/inbox?conversation=conv-1')
  await page.getByLabel('Assignee', { exact: true }).selectOption('Tumo Likotsi')
  await expect(page.getByLabel('Assignee', { exact: true })).toHaveValue('Tumo Likotsi')
  await page.locator('input[type=file]').setInputFiles({ name: 'receipt.pdf', mimeType: 'application/pdf', buffer: Buffer.from('fictional file') })
  await expect(page.getByLabel('Write a customer reply')).toContainText('[Attachment reference: receipt.pdf]')
  await page.getByRole('button', { name: 'Send reply', exact: true }).click()
  await expect(page.locator('.message-bubble').getByText('Thank you for the update. Please keep me informed.')).toBeVisible()
  await expect(page.locator('.delivery-state').last()).toHaveText('Saved')
  await page.getByRole('button', { name: 'Resolve', exact: true }).click()
  await page.getByRole('link', { name: 'Overview', exact: true }).click()
  await expect(page.locator('.report-metric').filter({ hasText: 'Resolved cases' }).locator('strong')).toHaveText('2')
  await expect(page.getByRole('button', { name: /Reset/i })).toHaveCount(0)
})

test('prototype remains usable when browser storage is blocked', async ({ page }) => {
  await page.addInitScript(() => { for (const name of ['localStorage', 'sessionStorage']) Object.defineProperty(window, name, { get() { throw new DOMException('Blocked', 'SecurityError') } }) })
  await page.goto('/inbox')
  await expect(page.getByRole('heading', { name: /Inbox/ })).toBeVisible()
  await page.getByLabel('Write a customer reply').fill('Memory-only message')
  await page.getByRole('button', { name: 'Send reply', exact: true }).click()
  await expect(page.locator('.message-bubble').getByText('Memory-only message')).toBeVisible()
})
