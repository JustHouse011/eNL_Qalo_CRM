import {test,expect} from '@playwright/test'
test.skip(process.env.QALO_RECOVERY_CONTRACT !== '1', 'Requires the explicit opt-in contract test server')
// These are contract mocks only: no real staff identity service or email delivery is asserted.
for(const brand of ['qalo','enl']) test(`${brand}: neutral request and browser email validation`,async({page})=>{
  let requests=0
  await page.route('**/api/staff-auth/recovery/request',async route=>{
    const body=route.request().postDataJSON();expect(body.brand).toBe(brand);expect(Object.keys(body).sort()).toEqual(['brand','email']);requests++
    await route.fulfill({status:202,json:{accepted:true}})
  })
  await page.goto(`/${brand}/forgot-password`)
  await page.getByLabel('Email address').fill('not-an-email')
  await page.getByRole('button',{name:'Send Reset Link'}).click();expect(requests).toBe(0)
  await page.getByLabel('Email address').fill('unknown@example.invalid')
  await page.getByRole('button',{name:'Send Reset Link'}).click()
  await expect(page.getByText("If an account exists for this email address, you'll receive password reset instructions shortly.",{exact:true})).toBeVisible()
  expect(requests).toBe(1)
})
test('server-validated token, policy, confirmation and successful completion without sign-in',async({page})=>{
  const token='contract-test-token-not-a-real-credential';let completed=0
  await page.route('**/api/staff-auth/recovery/validate',async route=>{expect(route.request().postDataJSON()).toEqual({token,brand:'qalo'});await route.fulfill({json:{valid:true,policy:{minLength:12,maxLength:128}}})})
  await page.route('**/api/staff-auth/recovery/complete',async route=>{expect(route.request().postDataJSON()).toEqual({token,brand:'qalo',password:'long test passphrase'});completed++;await route.fulfill({json:{updated:true}})})
  await page.goto(`/qalo/reset-password#token=${token}`)
  await expect(page.getByLabel('New password',{exact:true})).toBeEnabled()
  await expect(page).toHaveURL(/\/qalo\/reset-password$/)
  await page.getByLabel('New password',{exact:true}).fill('short')
  await page.getByLabel('Confirm new password',{exact:true}).fill('short')
  await page.getByRole('button',{name:'Update Password'}).click()
  await expect(page.getByRole('alert')).toContainText('at least 12')
  await page.getByLabel('New password',{exact:true}).fill('long test passphrase')
  await page.getByRole('button',{name:'Show new password'}).click()
  await expect(page.getByLabel('New password',{exact:true})).toHaveAttribute('type','text')
  await page.getByRole('button',{name:'Update Password'}).click()
  await expect(page.getByRole('alert')).toHaveText('Passwords do not match.')
  await page.getByLabel('Confirm new password',{exact:true}).fill('long test passphrase')
  await page.getByRole('button',{name:'Update Password'}).click()
  await expect(page.getByRole('heading',{name:'Password updated successfully.'})).toBeVisible()
  expect(completed).toBe(1)
  expect(await page.evaluate(t=>[...Object.values(localStorage),...Object.values(sessionStorage)].some(v=>v.includes(t)),token)).toBe(false)
  await expect(page).toHaveURL(/\/qalo\/reset-password$/)
  await page.getByRole('link',{name:'Back to Sign In'}).click();await expect(page).toHaveURL(/\/qalo\/signin$/)
})
test('expired links and server rejection of reused tokens never show success',async({page})=>{
  await page.route('**/api/staff-auth/recovery/validate',r=>r.fulfill({status:410,json:{}}))
  await page.goto('/enl/reset-password#token=expired-contract-token')
  await expect(page.getByRole('alert')).toContainText('invalid or expired')
  await expect(page.getByRole('button',{name:'Update Password'})).toBeDisabled()
  await page.unroute('**/api/staff-auth/recovery/validate')
  await page.route('**/api/staff-auth/recovery/validate',r=>r.fulfill({json:{valid:true,policy:{minLength:12,maxLength:128}}}))
  await page.route('**/api/staff-auth/recovery/complete',r=>r.fulfill({status:410,json:{}}))
  await page.goto('/enl/reset-password#token=reused-contract-token')
  await page.getByLabel('New password',{exact:true}).fill('long test passphrase');await page.getByLabel('Confirm new password',{exact:true}).fill('long test passphrase')
  await page.getByRole('button',{name:'Update Password'}).click();await expect(page.getByRole('alert')).toContainText('invalid or has expired')
  await expect(page.getByRole('heading',{name:'Password updated successfully.'})).toHaveCount(0)
})
test('rate limiting and SPA HTML fallback are not mistaken for email delivery',async({page})=>{
  await page.route('**/api/staff-auth/recovery/request',r=>r.fulfill({status:429,json:{}}))
  await page.goto('/qalo/forgot-password');await page.getByLabel('Email address').fill('unknown@example.invalid');await page.getByRole('button',{name:'Send Reset Link'}).click();await expect(page.getByRole('alert')).toContainText('Too many attempts')
  await page.unroute('**/api/staff-auth/recovery/request');await page.route('**/api/staff-auth/recovery/request',r=>r.fulfill({status:200,contentType:'text/html',body:'<html>SPA</html>'}))
  await page.getByRole('button',{name:'Send Reset Link'}).click();await expect(page.getByRole('alert')).toContainText('service is unavailable')
})
