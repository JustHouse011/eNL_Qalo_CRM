import {test,expect} from '@playwright/test'
for(const brand of ['qalo','enl']) test(`${brand}: recovery is honestly unavailable without a backend`,async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'})
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  const calls:string[]=[];page.on('request',r=>{if(r.url().includes('/api/staff-auth/'))calls.push(r.url())})
  await page.goto(`/${brand}/signin`)
  await expect(page.getByText('Looking for help? Contact support',{exact:true})).toHaveCount(0)
  await page.getByRole('link',{name:'Forgot password?',exact:true}).click()
  await expect(page).toHaveURL(new RegExp(`/${brand}/forgot-password$`))
  await expect(page.getByRole('heading',{name:'Forgot your password?',exact:true})).toBeVisible()
  await expect(page.getByRole('status')).toContainText('not available yet')
  await expect(page.getByRole('button',{name:'Send Reset Link'})).toBeDisabled()
  await expect(page.locator('.login-platform-brands img')).toHaveCount(2)
  await page.screenshot({path:`test-results/recovery-${brand}-desktop.png`,animations:'disabled'})
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:`test-results/recovery-${brand}-mobile.png`})
  await page.getByRole('link',{name:'Back to Sign In'}).click()
  await expect(page).toHaveURL(new RegExp(`/${brand}/signin$`))
  await page.goto(`/${brand}/reset-password#token=unused-test-fragment`)
  await expect(page).toHaveURL(new RegExp(`/${brand}/reset-password$`))
  await expect(page.getByRole('button',{name:'Update Password'})).toBeDisabled()
  await expect(page.getByLabel('New password',{exact:true})).toBeDisabled()
  expect(await page.evaluate(()=>Object.values(localStorage).some(v=>v.includes('unused-test-fragment')))).toBe(false)
  expect(calls).toEqual([])
  expect(errors).toEqual([])
})
