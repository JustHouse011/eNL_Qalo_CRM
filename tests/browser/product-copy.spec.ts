test('known legacy fixture copy is migrated without losing edits or business wording', async ({ page }) => {
  await page.goto('/inbox?conversation=conv-1')
  await page.getByLabel('Write a customer reply').fill('Please review the sample fabric order.')
  await page.getByRole('button', { name: 'Send reply', exact: true }).click()
  await expect(page.locator('.message-bubble').getByText('Please review the sample fabric order.')).toBeVisible()
  await page.evaluate(() => {
    const key = 'qalo-frontend-demo-v1'
    const data = JSON.parse(localStorage.getItem(key)!)
    delete data.presentationVersion
    const c = data.conversations.find((c: { id: string }) => c.id === 'conv-1')
    c.order.payment = 'Paid (simulated)'
    c.order.request = 'Review requested (simulated)'
    c.messages[0].text = '[Simulated reply] We have recorded your enquiry for the support team.'
    data.rules[0].name = 'Mock refund routing'
    localStorage.setItem(key, JSON.stringify(data))
  })
  await page.reload()
  await expect(page.locator('.message-bubble').getByText('Please review the sample fabric order.')).toBeVisible()
  await expect(page.getByText('Payment:', { exact: false })).toContainText('Awaiting verification')
  await auditCopy(page)
  await page.goto('/automations')
  await expect(page.getByRole('heading', { name: 'Refund enquiries' })).toBeVisible()
  await auditCopy(page)
})

