import { expect, test } from '@playwright/test'
import { selectWorkspace } from '../helpers/workspaceSelector'
import { ENL_WORKSPACE_ID, QALO_WORKSPACE_ID } from '../../src/lib/workspaceTypes'

test('desktop rail preserves both workspaces, navigation, badges and report space', async ({ page }) => {
  test.setTimeout(120000)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 1440, height: 960 })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/reports')
  const sidebar = page.getByRole('complementary', { name: 'Workspace navigation' })
  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  const reports = nav.getByRole('link', { name: 'Reports & Analytics', exact: true })
  const toggle = page.getByRole('button', { name: 'Collapse sidebar', exact: true })
  const workspace = page.getByRole('combobox', { name: 'Switch workspace' })
  const railTooltip = page.getByRole('tooltip')
  const reportPage = page.locator('.analytics-page')
  const routes = () => nav.getByRole('link').evaluateAll(links => links.map(link => link.getAttribute('href')))

  await expect(sidebar).toHaveCSS('width', '256px')
  await expect(sidebar.locator('.official-logo')).toBeVisible()
  await expect(sidebar.locator('.side-section-label').first()).toBeVisible()
  await expect(reports.locator('.nav-label')).toBeVisible()
  const expandedWidth = (await reportPage.boundingBox())!.width
  const expandedRoutes = await routes()
  await toggle.click()
  await expect(sidebar).toHaveCSS('width', '76px')
  await expect(sidebar.locator('.sidebar-brand-symbol img')).toBeVisible()
  expect((await reportPage.boundingBox())!.width - expandedWidth).toBeCloseTo(180, 0)
  expect(await routes()).toEqual(expandedRoutes)
  await expect(nav.locator('.nav-link > svg')).toHaveCount(expandedRoutes.length)
  await expect(reports.locator('.nav-label')).toBeHidden()
  await expect(sidebar.locator('.side-section-label').first()).toBeHidden()
  await expect(workspace.locator('.workspace-select-label')).toBeHidden()
  await expect(workspace.locator('.workspace-trigger-avatar')).toBeVisible()
  const inbox = nav.getByRole('link', { name: 'Inbox', exact: true })
  await expect(inbox.locator('.nav-badge')).toHaveText(/^\d+$/)
  await expect(inbox.locator('.nav-badge')).toBeVisible()
  const inboxBox = (await inbox.boundingBox())!
  const iconBox = (await inbox.locator('svg').boundingBox())!
  expect(iconBox.x + iconBox.width / 2).toBeCloseTo(inboxBox.x + inboxBox.width / 2, 0)
  await inbox.hover()
  await expect(railTooltip).toHaveText('Inbox')
  expect((await railTooltip.boundingBox())!.x).toBeGreaterThan((await sidebar.boundingBox())!.x + 76)
  await page.keyboard.press('Escape')
  await expect(railTooltip).toBeHidden()
  await inbox.click()
  await expect(page).toHaveURL(/\/inbox$/)
  await expect(inbox).toHaveAttribute('aria-current', 'page')
  await reports.focus()
  await expect(railTooltip).toHaveText('Reports & Analytics')
  await page.keyboard.press('Enter')
  await expect(reports).toHaveAttribute('aria-current', 'page')
  await page.reload()
  await expect(sidebar).toHaveCSS('width', '76px')

  page.once('dialog', dialog => dialog.accept())
  await selectWorkspace(page, ENL_WORKSPACE_ID)
  await expect(workspace).toHaveAttribute('data-workspace-id', ENL_WORKSPACE_ID)
  await expect(sidebar).toHaveCSS('width', '76px')
  await expect(sidebar.locator('.sidebar-brand-crest')).toBeVisible()
  await expect(page.getByRole('tab', { name: 'Support Performance' })).toBeVisible()
  const bankingReportsWidth = (await reportPage.boundingBox())!.width
  await page.getByRole('button', { name: 'Expand sidebar', exact: true }).click()
  await expect(sidebar).toHaveCSS('width', '256px')
  expect(bankingReportsWidth - (await reportPage.boundingBox())!.width).toBeCloseTo(180, 0)
  await expect(workspace.locator('.workspace-select-label')).toHaveText('eNL Mutual Bank')
  const bankRoutes = await routes()
  await toggle.click()
  expect(await routes()).toEqual(bankRoutes)
  for (const [name, route] of [
    ['Support Tickets', '/tickets'],
    ['Complaints & Disputes', '/complaints'],
    ['Banking Products', '/banking-products'],
    ['Agents & Departments', '/team'],
    ['Reports & Analytics', '/reports'],
  ]) {
    const link = nav.getByRole('link', { name, exact: true })
    await link.click()
    await expect(page).toHaveURL(new RegExp(route + '$'))
    await expect(link).toHaveAttribute('aria-current', 'page')
  }
  await expect(page.getByRole('tab', { name: 'Support Performance' })).toBeVisible()
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await expect(page.locator('.app-shell')).not.toHaveClass(/theme-light/)
  await expect(reports).toHaveCSS('background-image', /^linear-gradient/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(1440)
  await page.screenshot({ path: 'test-results/sidebar-enl-compact-dark.png', animations: 'disabled' })
  await sidebar.getByRole('button', { name: 'Log Out', exact: true }).click()
  await expect(page).toHaveURL(/\/enl\/signin$/)
  expect(errors).toEqual([])
})

test('mobile drawer keeps full labels and preserves the desktop preference', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 900, height: 900 })
  await page.goto('/reports')
  const sidebar = page.locator('#workspace-navigation')
  await expect(sidebar).toHaveCSS('width', '76px')
  await page.getByRole('button', { name: 'Expand sidebar', exact: true }).click()
  await expect(sidebar).toHaveCSS('width', '256px')
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  const opener = page.getByRole('button', { name: 'Open navigation', exact: true })
  await expect(opener).toHaveAttribute('aria-expanded', 'false')
  await opener.click()
  const drawer = page.getByRole('dialog', { name: 'Workspace navigation' })
  await expect(drawer).toBeVisible()
  await expect(drawer).toHaveCSS('width', '280px')
  await expect(drawer.locator('.official-logo')).toBeVisible()
  const inbox = drawer.getByRole('link', { name: 'Inbox', exact: true })
  await expect(inbox.locator('.nav-label')).toBeVisible()
  await expect(drawer.locator('.workspace-select-label')).toBeVisible()
  await expect(drawer.getByRole('button', { name: 'Log Out' }).locator('span')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(opener).toBeFocused()
  await opener.click()
  await inbox.click()
  await expect(page).toHaveURL(/\/inbox$/)
  await expect(opener).toHaveAttribute('aria-expanded', 'false')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.setViewportSize({ width: 1440, height: 960 })
  await expect(sidebar).toHaveCSS('width', '76px')
  await expect(page.getByRole('combobox', { name: 'Switch workspace' })).toHaveAttribute('data-workspace-id', QALO_WORKSPACE_ID)
})

test('a Qalo-only agent can open the compact switcher without gaining management links', async ({ page }) => {
  await page.goto('/overview')
  await page.evaluate(({ workspace, user }) => {
    const store = JSON.parse(localStorage.getItem('qalo-workspaces-v2')!)
    for (const membership of store.memberships) {
      if (membership.userId === user && membership.workspaceId !== workspace) membership.status = 'inactive'
    }
    localStorage.setItem('qalo-workspaces-v2', JSON.stringify(store))
    localStorage.setItem('qalo-sidebar', 'collapsed')
  }, { workspace: QALO_WORKSPACE_ID, user: 'user-agent-2' })
  await page.goto('/dev/session')
  await page.getByRole('combobox', { name: 'Account', exact: true }).selectOption('user-agent-2')
  await page.getByRole('button', { name: 'Start session', exact: true }).click()
  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  await expect(nav.getByRole('link', { name: 'Inbox', exact: true })).toBeVisible()
  await expect(nav.getByRole('link', { name: 'Reports & Analytics', exact: true })).toHaveCount(0)
  await expect(nav.getByRole('link', { name: 'Agents & Departments', exact: true })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Switch workspace' }).click()
  const options = page.getByRole('listbox').getByRole('option')
  await expect(options).toHaveCount(1)
  await expect(options.first()).toHaveAttribute('data-workspace-id', QALO_WORKSPACE_ID)
})
