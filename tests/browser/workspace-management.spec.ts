  await expect(page.getByRole('button', { name: 'Deactivate', exact: true })).toBeVisible()
  page.on('dialog', d => d.accept())
  await page.getByRole('row').filter({ has: page.getByRole('cell', { name: 'Bongani Nombamba', exact: true }) }).getByRole('button', { name: 'Remove member' }).click()
  await expect(page.getByRole('cell', { name: 'Bongani Nombamba', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toBeVisible()
