test('switch cancellation preserves a reply draft; confirmed switches clear it and old selections', async ({ page }) => {
  const { service, id } = fixture()
  await page.addInitScript(store => { if (!localStorage.getItem('qalo-workspaces-v2')) localStorage.setItem('qalo-workspaces-v2', JSON.stringify(store)) }, service.registry())
  await page.goto('/inbox?conversation=conv-1')
  const reply = page.getByLabel('Write a customer reply')
  await reply.fill('Unsent Qalo draft')
  page.once('dialog', d => d.dismiss())
  await selectWorkspace(page, id)
  await expect(reply).toHaveValue('Unsent Qalo draft')
  await expect(page.getByLabel('Switch workspace')).toHaveAttribute('data-workspace-id', QALO_WORKSPACE_ID)
  page.once('dialog', d => d.accept())
  await selectWorkspace(page, id)
  await expect(reply).toHaveCount(0)
  await expect(page).toHaveURL(/\/inbox$/)
  await expect(page.getByText('Lerato Mokoena', { exact: true })).toHaveCount(0)
  page.once('dialog', d => d.accept())
  await selectWorkspace(page, QALO_WORKSPACE_ID)
  await expect(reply).toHaveValue('')
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('qalo-workspaces-v2')!))
  expect(JSON.stringify(saved)).not.toContain('Unsent Qalo draft')
  expect(saved.snapshots[id].conversations).toEqual([])
})
