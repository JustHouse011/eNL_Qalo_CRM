async function selectProfile(page: Page, role: string) {
  const previous = page.url()
  const id = ({ Admin: 'user-agent-1', Supervisor: 'user-agent-2', Agent: 'user-agent-3', 'Platform Super Admin': 'user-agent-1' } as Record<string, string>)[role] || role.replace('user:', '')
  await page.goto('/dev/session')
  await page.getByLabel('Preview identity').selectOption(id)
  await page.getByRole('button', { name: 'Start mock session' }).click()
  await page.goto(previous)
}
const draft: WorkspaceDraft = { name: 'Independent support', slug: 'independent-support', description: 'Independent customer support', type: 'Organisation', logo: null, primaryColor: '#246789', secondaryColor: '#68ab89' }
function fixture() {
  const values = new Map<string, string>()
  const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value) } }
  const service = createSupportService(() => storage)
  const before = service.registry().snapshots[QALO_WORKSPACE_ID]
  service.manage(platformPreview.id, { kind: 'create', draft, administratorId: 'user-agent-1' })
  const id = service.registry().workspaces.find(w => w.slug === draft.slug)!.id
  return { service, storage, before, id }
}
test('creation persists independent empty records, stable membership and exact Qalo data', () => {
  const { service, storage, before, id } = fixture()
  const next = createSupportService(() => storage).registry()
  expect(next.snapshots[id].conversations).toEqual([])
  expect(next.snapshots[id].contacts).toEqual([])
  expect(next.snapshots[id].tickets).toEqual([])
  expect(next.snapshots[id].departments).toEqual([])
  expect(next.snapshots[id].agents).toHaveLength(1)
  expect(next.snapshots[QALO_WORKSPACE_ID]).toEqual(before)
  expect(() => service.manage(platformPreview.id, { kind: 'create', draft, administratorId: 'user-agent-1' })).toThrow('already in use')
  expect(next.workspaces).toHaveLength(2)
})
test('metadata permissions, membership lifecycle and independent global Administrator access', () => {
  const { service, id } = fixture()
  expect(() => service.manage('user-agent-3', { kind: 'edit', workspaceId: id, draft })).toThrow('permission')
  service.manage('user-agent-1', { kind: 'edit', workspaceId: id, draft: { ...draft, name: 'Renamed', primaryColor: '#123456' } })
  expect(service.registry().workspaces.find(w => w.id === id)?.name).toBe('Renamed')
  service.manage('user-agent-1', { kind: 'remove-member', workspaceId: id, userId: 'user-agent-1' })
  expect(canInWorkspace(service.registry().users[0], service.registry().workspaces.find(w => w.id === id), [], 'manage-members')).toBe(true)
  service.manage('user-agent-1', { kind: 'member', workspaceId: id, userId: 'user-agent-1', role: 'agent', status: 'active' })
  expect(service.registry().users[0].role).toBe('administrator')
  service.manage('user-agent-1', { kind: 'member', workspaceId: id, name: 'Fictional administrator', role: 'supervisor', status: 'active' })
  const user = service.registry().users.find(u => u.name === 'Fictional administrator')!
  service.manage('user-agent-1', { kind: 'member', workspaceId: id, userId: user.id, role: 'supervisor', status: 'inactive' })
  service.manage('user-agent-1', { kind: 'remove-member', workspaceId: id, userId: user.id })
  expect(service.registry().memberships.filter(m => m.workspaceId === id)).toHaveLength(1)
  expect(service.registry().users.find(u => u.id === user.id)?.role).toBe('supervisor')
})
test('status preserves records and excludes inactive workspaces from member access', async () => {
  const { service, id } = fixture()
  const before = await service.readWorkspace(id)
  expect(() => service.manage('user-agent-3', { kind: 'status', workspaceId: id, status: 'inactive' })).toThrow('Platform')
  service.manage(platformPreview.id, { kind: 'status', workspaceId: id, status: 'inactive' })
  const store = service.registry()
  expect(canInWorkspace(store.users[2], store.workspaces.find(w => w.id === id), store.memberships, 'view')).toBe(false)
  await expect(service.updateWorkspace(id, d => d)).rejects.toThrow('inactive')
  expect(() => service.selectWorkspace(id)).toThrow('inactive')
  expect(await service.readWorkspace(id)).toEqual(before)
  service.manage(platformPreview.id, { kind: 'status', workspaceId: id, status: 'active' })
  service.selectWorkspace(id)
  expect(service.registry().activeWorkspaceId).toBe(id)
})
test('delayed command keeps origin after workspace preference changes', async () => {
  const { service, id } = fixture()
  const before = await service.readWorkspace(id)
  const origin = QALO_WORKSPACE_ID
  const delayed = Promise.resolve().then(() => service.updateWorkspace(origin, d => ({ ...d, contacts: d.contacts.map((c, i) => i ? c : { ...c, name: 'Delayed update' }) })))
  service.selectWorkspace(id)
  await delayed
  expect(await service.readWorkspace(id)).toEqual(before)
  expect((await service.readWorkspace(origin)).contacts[0].name).toBe('Delayed update')
})
