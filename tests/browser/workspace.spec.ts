import { test, expect } from '@playwright/test'

test('customer chat, agent reply, note privacy, ticket conversion and persistence', async ({ page, context }) => {
  await page.goto('/inbox')
  await expect(page.getByRole('heading', { name: /Inbox/ })).toBeVisible()
  const customer = await context.newPage()
  await customer.goto('/chat')
  await customer.getByLabel('Business area', { exact: true }).selectOption('store')
  await customer.getByLabel('Your name').fill('Test Customer')
  await customer.getByLabel('Email', { exact: true }).fill('customer@example.co.za')
  await customer.getByLabel('Message', { exact: true }).fill('Please help with my delivery')
  await customer.getByRole('button', { name: 'Send message' }).click()
  await page.getByRole('button', { name: /Test Customer/ }).click()
  await page.getByRole('button', { name: 'Assign to me' }).click()
  await page.getByLabel('Write a customer reply').fill('Your support request is with us.')
  await page.getByRole('button', { name: 'Send reply', exact: true }).click()
  await expect(customer.getByText('Your support request is with us.')).toBeVisible()
  await page.getByRole('button', { name: 'Reply', exact: true }).click()
  await page.getByLabel('Write an internal note').fill('PRIVATE: agent-only context')
  await page.getByRole('button', { name: 'Add internal note', exact: true }).click()
  await expect(page.getByText('PRIVATE: agent-only context', { exact: true })).toBeVisible()
  await customer.reload()
  await expect(customer.getByText('Your support request is with us.')).toBeVisible()
  await expect(customer.getByText('PRIVATE: agent-only context')).toHaveCount(0)
  await page.getByRole('button', { name: 'Create Ticket', exact: true }).click()
  await page.getByLabel('Subject', { exact: true }).fill('Delivery follow-up')
  await page.getByRole('button', { name: 'Create ticket', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tickets', exact: true })).toBeVisible()
  await page.getByText('Linked conversation: Test Customer').click()
  await page.getByRole('link', { name: 'Open conversation', exact: true }).click()
  await page.getByRole('button', { name: 'Resolve', exact: true }).click()
  await expect(customer.getByText(/Your conversation is resolved/)).toBeVisible()
  await page.goto('/tickets')
  await page.getByRole('button', { name: /Delivery follow-up/ }).click()
  await page.getByText('Linked conversation: Test Customer').click()
  await expect(page.locator('details').getByText('PRIVATE: agent-only context')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: /Delivery follow-up/ })).toBeVisible()
})

