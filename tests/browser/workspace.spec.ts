test('contact editing, CSV validation and real report download', async ({ page }) => {
  await page.goto('/contacts')
  await page.getByRole('button', { name: 'New contact' }).click()
  await page.getByLabel('name', { exact: true }).fill('New Customer')
  await page.getByLabel('email', { exact: true }).fill('new@example.co.za')
  await page.getByRole('button', { name: 'Save contact' }).click()
  await expect(page.getByRole('button', { name: /New Customer/ })).toBeVisible()
  await page.getByText('Import contacts from CSV').click()
  await page.getByLabel('Paste CSV').fill('name,email,organisation\nOther,new@example.co.za,Example')
  await page.getByRole('button', { name: 'Validate and import' }).click()
  await expect(page.getByRole('status')).toContainText('Duplicate email')
  await page.goto('/reports')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export report' }).click()
  expect((await download).suggestedFilename()).toBe('support-report.csv')
})

test('automation routes new chats and pipeline changes persist', async ({ page, context }) => {
  await page.goto('/automations')
  await page.getByRole('button', { name: 'Create routing rule' }).click()
  await page.getByLabel('Rule name').fill('Delivery routing')
  await page.getByLabel('Message contains').fill('delivery')
  await page.locator('form').filter({ hasText: 'Create routing rule' }).getByLabel('Business area').selectOption('store')
  await page.getByLabel('Destination queue').selectOption('Deliveries')
  await page.locator('form').filter({ hasText: 'Create routing rule' }).getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Delivery routing' })).toBeVisible()
  await page.goto('/settings')
  await page.getByRole('button', { name: 'Queues', exact: true }).click()
  await page.getByLabel('Assignment method').selectOption('round-robin')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Changes saved')
  const customer = await context.newPage(); await customer.goto('/chat')
  await customer.getByLabel('Business area', { exact: true }).selectOption('store')
  await customer.getByLabel('Your name').fill('Routing Customer')
  await customer.getByLabel('Email', { exact: true }).fill('route@example.co.za')
  await customer.getByLabel('Message', { exact: true }).fill('A delivery question')
  await customer.getByRole('button', { name: 'Send message' }).click()
  await page.goto('/inbox'); await page.getByRole('button', { name: /Routing Customer/ }).click()
  await expect(page.getByLabel('Department', { exact: true })).toHaveValue('Deliveries')
  await expect(page.getByLabel('Assignee', { exact: true })).not.toHaveValue('')
  await page.goto('/pipeline')
  await page.getByLabel('Enquiry title').fill('Participation enquiry')
  await page.getByRole('button', { name: 'Add enquiry' }).click()
  await page.getByLabel('Support stage for Participation enquiry').selectOption('Support completed')
  await expect(page.getByLabel('Support stage for Participation enquiry')).toHaveValue('Support completed')
  await page.reload()
  await expect(page.getByLabel('Support stage for Participation enquiry')).toHaveValue('Support completed')
})

